#!/usr/bin/env python3
"""mkovl.py - building bsvm with overlays (vm/ovl.b16).

    mkovl.py stubs OUT                 out/ovl_stubs.b16: overlay entry stubs for the resident part
    mkovl.py keep OUT                  out/ovl_keep.b16: resident functions that are called by overlays
    mkovl.py env MAP OUT               out/ovl_env.b16: resident names for overlays (extern fn, var at)
    mkovl.py overlay NAME OUT          build the overlay vm/ov_NAME.b16 into OUT (the image for the window)
    mkovl.py pack OUT IMG...           out/bsvm.ovl: the overlay file, in the order of the OV_* numbers

The resident part is built with -n so that the functions called only by
overlays end up in the image. An overlay includes sysdefs.b16, bsdefs.b16, util.b16, types.b16 itself (their functions get
their own copies in the overlay) and ovl_env.b16 - the declarations of the resident part: functions as extern
fn, global variables as var NAME at ADDRESS: TYPE. The labels of the resident functions are added to the
overlay's assembler as .equ lines from the memory map of the resident part."""
import os, re, subprocess, struct, sys

B = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.dirname(B)
VM = os.environ.get('BSVM_SRC', os.path.join(B, 'vm'))   # another directory - a build for checking (stress)
OVERLAYS = ['fs', 'sys', 'gc', 'init']           # order = OV_FS, OV_SYS, OV_GC, OV_INIT (vm/types.b16)
OV_CONST = {'fs': 'OV_FS', 'sys': 'OV_SYS', 'gc': 'OV_GC', 'init': 'OV_INIT'}
# image address: the window is on page 6, the init loader is on page 5 (ovl.b16, init_run)
OV_AT = {'init': 0xA000}
# resident VM sources (its own; the common libraries are included by the overlay itself)
RESIDENT = ['heap', 'map', 'value', 'io', 'interp', 'ops', 'lib', 'libstr', 'ovl', 'bsvm']
OV_BASE = 0xC000
OV_LIMIT = 0xE000

def ov_table(name):
    s = open(os.path.join(VM, 'ov_%s.b16' % name), encoding='utf-8').read()
    m = re.search(r'var ov_table: \[\w+\]ptr fn\(\): uint = \{([^}]*)\}', s)
    return [x.strip() for x in m.group(1).split(',') if x.strip()]

def stub_names():
    return {n for o in OVERLAYS for n in ov_table(o)}

def cmd_stubs(out):
    lines = ['// ovl_stubs.b16 - generated by tools/mkovl.py: overlay entries for the built-in',
             '// function and method tables of the resident part.', '']
    for o in OVERLAYS:
        if o in OV_AT: continue                  # init is called directly (init_run)
        for i, n in enumerate(ov_table(o)):
            lines.append('fn %s(): uint { return ov_call(%s, %d) }' % (n, OV_CONST[o], i))
    open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')

def read_map(path):
    labels = {}
    f = False
    for l in open(path):
        if '== Objects by address' in l: f = True; continue
        if f and l.startswith('$'):
            p = l.split()
            name = p[4] if len(p) >= 5 and p[1].startswith('$') else p[3] if len(p) >= 4 else '@'
            if not name.startswith('@'):
                labels[name] = int(p[0][1:], 16)
    return labels

def cmd_env(mapfile, out):
    labels = read_map(mapfile) if mapfile else None
    skip = stub_names()
    res = ['// ovl_env.b16 - generated by tools/mkovl.py from the resident sources and the memory map:',
           '// the resident part of bsvm for the overlays.', '']
    for src in RESIDENT:
        text = open(os.path.join(VM, src + '.b16'), encoding='utf-8').read()
        lines = text.split('\n')
        i = 0
        while i < len(lines):
            l = lines[i]
            if l.startswith('const '):
                res.append(l)
            elif l.startswith('var ') and ' at ' in l.split(':')[0]:
                res.append(l)
            elif l.startswith('var '):
                m = re.match(r'var ([\w, ]+):\s*([^=]+?)\s*(=.*)?$', l)
                if m:
                    for n in [x.strip() for x in m.group(1).split(',')]:
                        a = 0 if labels is None else labels.get(n, labels.get('__' + n))
                        if a is None: raise SystemExit('mkovl: %s: no address for %s' % (src, n))
                        res.append('var %s at $%04X: %s' % (n, a, m.group(2).strip()))
            elif re.match(r'(export )?fn \w+', l):
                m = re.match(r'(?:export )?(fn (\w+)\(.*?\)(?:\s*:\s*[^{]+?)?)\s*\{', l)
                if not m: raise SystemExit('mkovl: %s: cannot parse %r' % (src, l))
                if m.group(2) not in skip and m.group(2) != 'main':
                    res.append('extern ' + m.group(1).strip())
            i += 1
    open(out, 'w', encoding='utf-8').write('\n'.join(res) + '\n')

def cmd_overlay(name, out, mapfile):
    base = OV_AT.get(name, OV_BASE)
    limit = base + 0x2000
    d = os.path.dirname(os.path.abspath(out))
    main = os.path.join(d, 'ov_%s_main.b16' % name)
    # sysdefs.b16 rather than sys.b16: the call wrappers live in the resident part, the overlay takes their addresses
    # from the bsvm map (.equ below) instead of including sys.asm again
    open(main, 'w').write('// generated by tools/mkovl.py\ninclude "sysdefs.b16"\ninclude "bsdefs.b16"\n'
                          'include "util.b16"\ninclude "types.b16"\ninclude "ovl_env.b16"\n'
                          'include "ov_%s.b16"\n' % name)
    s = os.path.join(d, 'ov_%s.s' % name)
    inc = ['-I', d, '-I', VM, '-I', os.path.join(B, 'common'), '-I', os.path.join(R, 'monitor/user/lib'),
           '-I', os.path.join(R, 'monitor/kernel')]
    subprocess.run([os.path.join(R, 'b16c/b16c')] + inc + ['--target', 'kernel', '--code', '$%04X' % (base + 16),
                    main, '-o', s], check=True)
    asm = open(s).read()
    defined = set(re.findall(r'^([\w.]+):', asm, re.M)) | set(re.findall(r'^\s*\.equ\s+([\w.]+)', asm, re.M))
    labels = read_map(mapfile)
    extra = ['\t.equ  %s, $%04X' % (n, a) for n, a in sorted(labels.items()) if n not in defined and '.' not in n]
    open(s, 'w').write(asm + '\n; the resident part of bsvm (tools/mkovl.py)\n' + '\n'.join(extra) + '\n')
    img = os.path.join(d, 'ov_%s.img' % name)
    subprocess.run([os.path.join(R, 'cpu16/build/cpu16asm'), '--base', '$%04X' % (base + 16), '-m',
                    os.path.join(d, 'ov_%s.map' % name), '-o', img, s], check=True, capture_output=True)
    om = read_map(os.path.join(d, 'ov_%s.map' % name))
    end = om['__bss_end']
    if end > limit: raise SystemExit('mkovl: overlay %s too large: ends at $%04X' % (name, end))
    body = open(img, 'rb').read()
    hdr = struct.pack('<HHHH', ord('O') | ord('V') << 8, om['ov_table'], base + 16 + len(body), end) + b'\0' * 8
    open(out, 'wb').write(hdr + body)
    print('mkovl: overlay %-5s %5d bytes, ends at $%04X' % (name, len(hdr) + len(body), end))

# Resident-part functions that are called by overlays: overlays are compiled with declarations
# without addresses, and the names are extracted from their assembler. The file OUT refers to them with an asm insert, and they
# get into the image without the -n option (all functions are entry points).
def cmd_keep(out):
    d = os.path.dirname(os.path.abspath(out))
    cmd_env(None, os.path.join(d, 'ovl_env.b16'))
    resident = set()
    for src in RESIDENT:
        for l in open(os.path.join(VM, src + '.b16'), encoding='utf-8'):
            m = re.match(r'(?:export )?fn (\w+)', l)
            if m: resident.add(m.group(1))
    resident -= stub_names()
    used = set()
    inc = ['-I', d, '-I', VM, '-I', os.path.join(B, 'common'), '-I', os.path.join(R, 'monitor/user/lib'),
           '-I', os.path.join(R, 'monitor/kernel')]
    for name in OVERLAYS:
        main = os.path.join(d, 'ov_%s_main.b16' % name)
        open(main, 'w').write('include "sysdefs.b16"\ninclude "bsdefs.b16"\ninclude "util.b16"\ninclude "types.b16"\n'
                              'include "ovl_env.b16"\ninclude "ov_%s.b16"\n' % name)
        s = os.path.join(d, 'ov_%s_keep.s' % name)
        subprocess.run([os.path.join(R, 'b16c/b16c')] + inc + ['--target', 'kernel', '--code', '$C010', main, '-o', s],
                       check=True)
        asm = open(s).read()
        defined = set(re.findall(r'^([\w.]+):', asm, re.M))
        code = '\n'.join(re.sub(r';.*$', '', l) for l in asm.splitlines() if not l.strip().startswith('.line'))
        words = set(re.findall(r'(?<![\w.])([A-Za-z_][\w]*)(?![\w.])', code))
        for n in resident:
            if '__' + n in words and '__' + n not in defined: used.add('__' + n)
            elif n in words and n not in defined: used.add(n)
    lines = ['// ovl_keep.b16 - generated by tools/mkovl.py: the resident functions that are called by',
             '// the overlays (references from asm make them reachable; the function is not called).', '',
             'fn ovl_keep_refs() {', '    asm {']
    lines += ['        .word   %s' % n for n in sorted(used)]
    lines += ['    }', '}']
    open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')

def cmd_pack(out, imgs):
    data = [open(p, 'rb').read() for p in imgs]
    head = struct.pack('<HH', ord('B') | ord('S') << 8, len(data))
    off = len(head) + 4 * len(data)
    tab = b''
    for x in data:
        tab += struct.pack('<HH', off, len(x)); off += len(x)
    open(out, 'wb').write(head + tab + b''.join(data))

if __name__ == '__main__':
    a = sys.argv[1:]
    if a[0] == 'stubs': cmd_stubs(a[1])
    elif a[0] == 'env': cmd_env(a[1], a[2])
    elif a[0] == 'overlay': cmd_overlay(a[1], a[2], a[3])
    elif a[0] == 'pack': cmd_pack(a[1], a[2:])
    elif a[0] == 'keep': cmd_keep(a[1])
    else: raise SystemExit(__doc__)
