// gen_isa_js.cpp - generates a JavaScript description of the instruction set (cpu16_isa.hpp)
// and of the machine: the encoding, palette, ports, scancodes (cpu16_machine.hpp).
//
// There is one source of truth: cpu16_isa.hpp. The browser debugger gets from here the names,
// instruction classes, pseudo-instruction encodings and the validity table instead of rewriting them by hand.
//
// Build (from the project root): g++ -std=c++17 -O2 -Itools -o build/gen_isa_js debugger/src/gen_isa_js.cpp
// Run: ./gen_isa_js > isa.generated.js
//
// The validity table. The reason (cpu16::Reason) depends on the opcode, R2, MOD and only on the
// "class" of the R1 field: 0, 1..14 or 15. So instead of 65536 entries 4096*3 suffice,
// 4 bits per entry. The generator checks this compression on all 65536 words.

#include <cstdio>
#include <cstdlib>
#include <string>
#include <vector>

#include "cpu16_isa.hpp"
#include "cpu16_machine.hpp"

using namespace cpu16;

static unsigned r1Class(unsigned r1) { return r1 == 0 ? 0 : (r1 == 15 ? 2 : 1); }

static std::string base64(const std::vector<uint8_t>& d) {
    static const char* t = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    std::string out;
    for (size_t i = 0; i < d.size(); i += 3) {
        const unsigned v = (d[i] << 16) | ((i + 1 < d.size() ? d[i + 1] : 0) << 8) | (i + 2 < d.size() ? d[i + 2] : 0);
        out += t[(v >> 18) & 63];
        out += t[(v >> 12) & 63];
        out += i + 1 < d.size() ? t[(v >> 6) & 63] : '=';
        out += i + 2 < d.size() ? t[v & 63] : '=';
    }
    return out;
}

static const char* clsName(OpClass c) {
    switch (c) {
    case OpClass::Reserved: return "reserved";
    case OpClass::Load: return "load";
    case OpClass::Alu: return "alu";
    case OpClass::Shift: return "shift";
    case OpClass::ByteLoad: return "byteload";
    case OpClass::Store: return "store";
    case OpClass::Branch: return "branch";
    case OpClass::Trap: return "trap";
    case OpClass::Misc: return "misc";
    case OpClass::ShortBranch: return "shortbranch";
    }
    return "?";
}

int main() {
    // --- the reason table: index ((op<<7)|(r2<<3)|mod)*3 + R1 class
    std::vector<uint8_t> reason(4096 * 3, 0xFF);
    int reasonValidity[16];
    for (int i = 0; i < 16; i++) reasonValidity[i] = -1;
    for (unsigned w = 0; w < 65536; w++) {
        const Check c = check((uint16_t)w);
        const unsigned idx = (((w >> 11) << 7) | (fieldR2((uint16_t)w) << 3) | fieldMod((uint16_t)w)) * 3 + r1Class(fieldR1((uint16_t)w));
        const uint8_t r = (uint8_t)c.reason;
        if (reason[idx] == 0xFF) reason[idx] = r;
        else if (reason[idx] != r) {
            std::fprintf(stderr, "gen_isa_js: table compression is wrong for word %04X\n", w);
            return 1;
        }
        if (reasonValidity[r] < 0) reasonValidity[r] = (int)c.validity;
        else if (reasonValidity[r] != (int)c.validity) {
            std::fprintf(stderr, "gen_isa_js: reason %d corresponds to different classes\n", r);
            return 1;
        }
    }
    std::vector<uint8_t> packed(reason.size() / 2);
    for (size_t i = 0; i < packed.size(); i++) packed[i] = (uint8_t)(reason[2 * i] | (reason[2 * i + 1] << 4));

    std::printf("// Generated by gen_isa_js.cpp from cpu16_isa.hpp (specification, revision %d). Do not edit by hand.\n", SPEC_REVISION);
    std::printf("const ISA = (() => {\n");
    std::printf("  const opInfo = [\n");
    for (unsigned op = 0; op < OPCODE_COUNT; op++) {
        const OpInfo& o = OP_INFO[op];
        std::printf("    { name: %s, cls: \"%s\", byteOp: %s, writesR1: %s, setsFlags: %s },\n",
                    o.name ? ("\"" + std::string(o.name) + "\"").c_str() : "null", clsName(o.cls),
                    o.byteOp ? "true" : "false", o.writesR1 ? "true" : "false", o.setsFlags ? "true" : "false");
    }
    std::printf("  ];\n");
    std::printf("  const regNames = [");
    for (unsigned r = 0; r < REG_COUNT; r++) std::printf("%s\"%s\"", r ? ", " : "", REG_NAMES[r]);
    std::printf("];\n  const condNames = [");
    for (unsigned c = 0; c < 16; c++)
        std::printf("%s%s", c ? ", " : "", COND_NAMES[c].primary ? ("\"" + std::string(COND_NAMES[c].primary) + "\"").c_str() : "null");
    std::printf("];\n  const condAliases = [");
    for (unsigned c = 0; c < 16; c++)
        std::printf("%s%s", c ? ", " : "", COND_NAMES[c].alias ? ("\"" + std::string(COND_NAMES[c].alias) + "\"").c_str() : "null");
    std::printf("];\n  const pseudoNames = [");   // index = cpu16::Pseudo; 0 - none
    for (unsigned i = 0; i < PSEUDO_COUNT; i++)
        std::printf("%s%s", i ? ", " : "", PSEUDO_NAMES[i] ? ("\"" + std::string(PSEUDO_NAMES[i]) + "\"").c_str() : "null");
    std::printf("];\n  const miscNames = [");   // subcodes of the combined MISC opcode
    for (unsigned i = 0; i < MISC_COUNT; i++) std::printf("%s\"%s\"", i ? ", " : "", MISC_NAMES[i]);
    std::printf("];\n  const reasonText = [");
    for (int r = 0; r <= (int)Reason::BranchAutoinc; r++) std::printf("%s\"%s\"", r ? ", " : "", reasonText((Reason)r));
    std::printf("];\n  const reasonValidity = [");   // 0 - valid, 1 - reserved, 2 - constrained unpredictable
    for (int r = 0; r <= (int)Reason::BranchAutoinc; r++) std::printf("%s%d", r ? ", " : "", reasonValidity[r]);
    std::printf("];\n");
    std::printf("  const packed = Uint8Array.from(atob(\"%s\"), (c) => c.charCodeAt(0));\n", base64(packed).c_str());
    std::printf("  const OP = {");
    for (unsigned op = 0; op < OPCODE_COUNT; op++)
        if (OP_INFO[op].name && op != JXX) std::printf(" %s: %u,", OP_INFO[op].name, op);
    std::printf(" JXX: %u };\n", (unsigned)JXX);
    std::printf("  const pseudo = { NOP: 0x%04X, RET: 0x%04X, STI: 0x%04X, CLI: 0x%04X, STC: 0x%04X, CLC: 0x%04X, CMC: 0x%04X };\n",
                W_NOP, W_RET, W_STI, W_CLI, W_STC, W_CLC, W_CMC);
    std::printf("  const MISC = { NEG: %u, NOT: %u, BSX: %u, IRET: %u, WFI: %u, COUNT: %u };\n",
                (unsigned)MISC_NEG, (unsigned)MISC_NOT, (unsigned)MISC_BSX, (unsigned)MISC_IRET, (unsigned)MISC_WFI, MISC_COUNT);
    std::printf("  const encodePush = (r) => 0x%04X | (r << 7);\n", encodePush(0));
    std::printf("  const encodePop = (r) => 0x%04X | (r << 7);\n", encodePop(0));
    std::printf("  const encodeInc = (r) => 0x%04X | (r << 7);\n", encodeInc(0));
    std::printf("  const encodeDec = (r) => 0x%04X | (r << 7);\n", encodeDec(0));
    std::printf(
        "  function reason(w) {\n"
        "    const r1 = (w >> 7) & 15;\n"
        "    const i = (((w >> 11) << 7) | (w & 0x7F)) * 3 + (r1 === 0 ? 0 : r1 === 15 ? 2 : 1);\n"
        "    return (packed[i >> 1] >> ((i & 1) * 4)) & 15;\n"
        "  }\n"
        "  const hasOperand = (op) => [\"load\", \"alu\", \"shift\", \"byteload\", \"store\", \"branch\", \"trap\"].includes(opInfo[op & 31].cls);\n"
        "  function instrWords(w) {\n"
        "    const op = w >> 11, r2 = (w >> 3) & 15, mod = w & 7;\n"
        "    if (!hasOperand(op)) return 1;\n"
        "    return mod >= %u || (mod === %u && r2 === %u) ? 2 : 1;\n"
        "  }\n",
        (unsigned)M_ABS, (unsigned)M_POSTINC, (unsigned)IP);
    std::printf(
        "  return {\n"
        "    SPEC_REVISION: %d, VEC_BASE: 0x%04X, VEC_ERRCMD: %u,\n"
        "    LR: %u, SP: %u, IP: %u, FL: %u,\n"
        "    ZF: %u, CF: %u, SF: %u, IF: %u, OF: %u,\n"
        "    opInfo, regNames, condNames, condAliases, pseudoNames, miscNames, MISC, reasonText, reasonValidity, OP, pseudo,\n"
        "    encodePush, encodePop, encodeInc, encodeDec, reason, instrWords, hasOperand,\n"
        "    valid: (w) => reason(w) === 0,\n"
        "  };\n"
        "})();\n",
        SPEC_REVISION, VEC_BASE, VEC_ERRCMD, (unsigned)LR, (unsigned)SP, (unsigned)IP, (unsigned)FL,
        (unsigned)ZF, (unsigned)CF, (unsigned)SF, (unsigned)FIF, (unsigned)OF);
    // ---- the machine: encoding, palette, ports, scancodes (cpu16_machine.hpp)
    std::printf("const MACHINE = {\n  charset: [");
    for (int b = 0; b < 256; b++) std::printf("%s%u", b ? "," : "", (unsigned)CHARSET[b]);
    std::printf("],\n  palette: [");
    for (int i = 0; i < 8; i++) std::printf("%s\"#%06X\"", i ? ", " : "", PALETTE[i]);
    std::printf("],\n  scancodes: {");
    bool first = true;
    for (const auto& k : WEB_SCANCODES) { std::printf("%s%s: 0x%02X", first ? " " : ", ", k.name, k.scan); first = false; }
    std::printf(" },\n");
    std::printf("  PORT_DATA: 0x%04X, PORT_SCAN: 0x%04X, PORT_CTRL: 0x%04X, PORT_ATTR: 0x%04X, PORT_COL: 0x%04X,\n"
                "  PORT_ROW: 0x%04X, PORT_CMD: 0x%04X, PORT_COLS: 0x%04X, PORT_ROWS: 0x%04X, PORT_TIMER: 0x%04X,\n",
                PORT_DATA, PORT_SCAN, PORT_CTRL, PORT_ATTR, PORT_COL, PORT_ROW, PORT_CMD, PORT_COLS, PORT_ROWS, PORT_TIMER);
    std::printf("  IO_BASE: 0x%04X,\n", IO_BASE);
    std::printf("  PORT_MODS: 0x%04X, MOD_SHIFT: %u, MOD_CTRL: %u, MOD_ALT: %u, MOD_MASK: %u,\n",
                PORT_MODS, (unsigned)MOD_SHIFT, (unsigned)MOD_CTRL, (unsigned)MOD_ALT, (unsigned)MOD_MASK);
    std::printf("  PORT_SCRD: 0x%04X,\n", PORT_SCRD);
    std::printf("  RTC_TIME: 0x%04X, RTC_DATE: 0x%04X, RTC_STATUS: 0x%04X, RTC_CMD: 0x%04X, RTC_FIRST: 0x%04X, RTC_LAST: 0x%04X,\n"
                "  RTCC_READ: %u, RTCC_WRITE: %u, RTCC_WRITE_TIME: %u, RTCC_WRITE_DATE: %u, RTC_ERR: %u,\n"
                "  RTC_BASE_YEAR: %u, RTC_YEARS: %u, RTC_DAY: %u, RTC_DAYS: %u, RTC_PERIOD: %u, RTC_SECOND_US: %lld,\n",
                RTC_TIME, RTC_DATE, RTC_STATUS, RTC_CMD, RTC_FIRST, RTC_LAST, (unsigned)RTCC_READ, (unsigned)RTCC_WRITE,
                (unsigned)RTCC_WRITE_TIME, (unsigned)RTCC_WRITE_DATE, (unsigned)RTC_ERR, RTC_BASE_YEAR, RTC_YEARS,
                (unsigned)RTC_DAY, (unsigned)RTC_DAYS, (unsigned)RTC_PERIOD, (long long)RTC_SECOND_US);
    std::printf("  MMU_PAGE0: 0x%04X, MMU_CTRL: 0x%04X, MMU_FIRST: 0x%04X, MMU_LAST: 0x%04X, MMU_EN: %u,\n"
                "  PAGE_BITS: %u, PAGE_COUNT: %u, FRAME_COUNT: %u, PAGE_SIZE: %u, PHYS_SIZE: %u,\n",
                MMU_PAGE0, MMU_CTRL, MMU_FIRST, MMU_LAST, (unsigned)MMU_EN, PAGE_BITS, PAGE_COUNT, FRAME_COUNT,
                (unsigned)PAGE_SIZE, (unsigned)PHYS_SIZE);
    std::printf("  DK_STATUS: 0x%04X, DK_CMD: 0x%04X, DK_ERROR: 0x%04X, DK_DISK: 0x%04X, DK_COUNT: 0x%04X, DK_ADDR: 0x%04X,\n"
                "  DK_LBA_LO: 0x%04X, DK_LBA_HI: 0x%04X, DK_CTRL: 0x%04X, DK_DRIVES: 0x%04X, DK_FIRST: 0x%04X, DK_LAST: 0x%04X,\n",
                DK_STATUS, DK_CMD, DK_ERROR, DK_DISK, DK_COUNT, DK_ADDR, DK_LBA_LO, DK_LBA_HI, DK_CTRL, DK_DRIVES, DK_FIRST, DK_LAST);
    std::printf("  DKS_BUSY: %u, DKS_ERR: %u, DKS_DONE: %u, DKS_PRESENT: %u, DKS_RO: %u, DK_IEN: %u,\n"
                "  DKC_ACK: %u, DKC_READ: %u, DKC_WRITE: %u, DKC_INFO: %u, DKC_FLUSH: %u,\n"
                "  DKE_OK: %u, DKE_NODISK: %u, DKE_BADCMD: %u, DKE_RANGE: %u, DKE_BADADDR: %u, DKE_READONLY: %u, DKE_IO: %u,\n"
                "  DKI_RO: %u, DKI_REMOVABLE: %u, DKI_SMALL: %u,\n"
                "  SECTOR_SIZE: %u, DISK_COUNT: %u, DISK_LABEL_MAX: %u, DISK_INFO_SIZE: %u, DMA_LIMIT: 0x%04X,\n",
                DKS_BUSY, DKS_ERR, DKS_DONE, DKS_PRESENT, DKS_RO, (unsigned)DK_IEN, DKC_ACK, DKC_READ, DKC_WRITE, DKC_INFO,
                DKC_FLUSH, DKE_OK, DKE_NODISK, DKE_BADCMD, DKE_RANGE, DKE_BADADDR, DKE_READONLY, DKE_IO, DKI_RO,
                DKI_REMOVABLE, DKI_SMALL, SECTOR_SIZE, DISK_COUNT, DISK_LABEL_MAX, DISK_INFO_SIZE, (unsigned)DMA_LIMIT);
    std::printf("  COLS: %u, ROWS: %u, CTRL_TTY: %u, CTRL_CURSOR: %u, CTRL_ATTRMODE: %u, CTRL_MASK: %u,\n"
                "  CMD_CLS: %u, CMD_CLEOL: %u, CMD_CLEOS: %u, CMD_SCROLL_UP: %u, CMD_SCROLL_DOWN: %u,\n"
                "  ATTR_DEFAULT: %u, CTRL_DEFAULT: %u, KEY_QUEUE_MAX: %u, TIMER_PERIOD_US: %lld,\n};\n",
                SCREEN_COLS, SCREEN_ROWS, (unsigned)CTRL_TTY, (unsigned)CTRL_CURSOR, (unsigned)CTRL_ATTRMODE, (unsigned)CTRL_MASK,
                (unsigned)CMD_CLS, (unsigned)CMD_CLEOL, (unsigned)CMD_CLEOS, (unsigned)CMD_SCROLL_UP, (unsigned)CMD_SCROLL_DOWN,
                (unsigned)ATTR_DEFAULT, (unsigned)CTRL_DEFAULT, KEY_QUEUE_MAX, (long long)TIMER_PERIOD_US);
    return 0;
}
