#!/usr/bin/env python3
"""Rebuild the self-contained HTML from a debugger-only source archive.

The existing cpu16_debugger.html supplies only generated CPU16 ISA tables,
character data and the bundled standard library. All JS engine, assembler,
FS16 and UI code is read afresh from webdbg/src. For a full CPU16 checkout,
prefer build.py to regenerate the ISA tables from the canonical C++ sources.
"""
from pathlib import Path
import json
import re
import sys

base = Path(__file__).resolve().parent
built = base / "cpu16_debugger.html"
if not built.exists():
    sys.exit("build_local.py: a prebuilt cpu16_debugger.html is required")
old = built.read_text(encoding="utf8")
m = re.search(r"^const DEMO = (.*);$", old, re.M)
g = re.search(r"^const GLYPHS = (.*);$", old, re.M)
if not m or not g:
    sys.exit("build_local.py: embedded demo and glyph data not found")

demo = json.loads(m.group(1))
demo["source"] = (base / "src/demo.asm").read_text(encoding="utf8")
engine = (base / "src/engine.js").read_text(encoding="utf8").strip()
assembler = (base / "src/assembler.js").read_text(encoding="utf8").strip()
start = old.index("// BEGIN ENGINE\n") + len("// BEGIN ENGINE\n")
marker = "// engine.js - the debugger engine"
end = old.index(marker, start)
isa = old[start:end].strip()
if not isa.startswith("// Generated by gen_isa_js.cpp"):
    sys.exit("build_local.py: cannot identify bundled ISA tables")

tpl = (base / "src/debugger.template.html").read_text(encoding="utf8")
replacements = {
    "__DEMO__": json.dumps(demo, ensure_ascii=True, separators=(",", ":")),
    "__ROM_BYTES__": json.dumps(list((base / "src/rom.bin").read_bytes()), separators=(",", ":")),
    "__GLYPHS__": g.group(1),
    "/*__ISA__*/": isa,
    "/*__ENGINE__*/": engine,
    "/*__ASSEMBLER__*/": assembler,
    "/*__FS16__*/": (base / "src/fs16.js").read_text(encoding="utf8").strip() + "\n" +
                     (base / "src/fs16_ui.js").read_text(encoding="utf8").strip(),
}
for tag, value in replacements.items():
    if tpl.count(tag) != 1:
        sys.exit(f"build_local.py: expected exactly one {tag} marker")
    tpl = tpl.replace(tag, value)

output = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else built
output.write_text(tpl, encoding="utf8")
print(f"build_local.py: wrote {output} ({len(tpl.encode('utf8'))} bytes)")
